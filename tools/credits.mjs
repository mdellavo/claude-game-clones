// Writes a CREDITS.md for every game listing the Poly Pizza models it ships.
//   node tools/credits.mjs
// Each models/<name>.js starts with a comment naming its Poly Pizza ID; tools/model-credits.json maps the ID
// to the model's title, author and licence (read from its Poly Pizza page when the model was picked). Add a row
// there when adding a model. Vite games (xcom, zelda) get theirs in public/ so the build copies it into dist/.
// The devkit's "Credits" menu entry in each game shows the file.
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const DATA = JSON.parse(readFileSync(join(root, 'tools/model-credits.json'), 'utf8'));
const LICENCE_URL = { 'CC0 1.0': 'https://creativecommons.org/publicdomain/zero/1.0/', 'CC-BY 3.0': 'https://creativecommons.org/licenses/by/3.0/' };

const names = {};
for (const line of readFileSync(join(root, 'README.md'), 'utf8').split('\n')) {
  const m = line.match(/^\| \*\*(.+?)\*\*<br>`([^`]+)\/`/);
  if (m) names[m[2]] = m[1];
}
const games = readdirSync(root).filter((d) => !d.startsWith('.') && !d.startsWith('_') && statSync(join(root, d)).isDirectory() && existsSync(join(root, d, 'index.html')));

let missing = 0;
for (const g of games) {
  const name = names[g] || g;
  const pkg = existsSync(join(root, g, 'package.json')) ? JSON.parse(readFileSync(join(root, g, 'package.json'), 'utf8')) : null;
  const vite = !!pkg?.scripts?.build?.includes('vite');
  const dir = join(root, g, vite ? 'public' : '');
  const mdir = join(dir, 'models');
  // model ID -> the file names that use it
  const used = new Map();
  for (const f of existsSync(mdir) ? readdirSync(mdir).filter((f) => f.endsWith('.js')).sort() : []) {
    const id = readFileSync(join(mdir, f), 'utf8').slice(0, 400).match(/Poly Pizza ([\w-]{6,}),/)?.[1];
    if (!id || !DATA[id]) { console.warn(`${g}/models/${f}: ${id ? 'no entry for ' + id + ' in tools/model-credits.json' : 'no Poly Pizza ID in its header'}`); missing++; continue; }
    used.set(id, [...(used.get(id) || []), f.slice(0, -3)]);
  }
  const rows = [...used].map(([id, files]) => ({ id, files, ...DATA[id] })).sort((a, b) => a.title.localeCompare(b.title));
  const lines = [`# ${name} credits`, ''];
  if (!rows.length) lines.push(`${name} uses no third-party models: everything on screen is built in code.`);
  else {
    const by = rows.filter((r) => r.licence.startsWith('CC-BY')).length;
    lines.push(`The 3D models come from [Poly Pizza](https://poly.pizza). ${by ? 'Those marked CC-BY are credited to their authors as the licence asks; the rest are CC0.' : 'All of them are CC0.'} Generated by \`tools/credits.mjs\`.`, '', '## Models', '');
    for (const r of rows) {
      lines.push(`- **[${r.title}](https://poly.pizza/m/${r.id})** by ${r.author} · [${r.licence}](${LICENCE_URL[r.licence]})`);
      lines.push(`  Used as ${r.files.map((f) => '`' + f + '`').join(', ')}`);
    }
  }
  writeFileSync(join(dir, 'CREDITS.md'), lines.join('\n') + '\n');
  console.log(`${g.padEnd(22)} ${String(rows.length).padStart(3)} models -> ${join(dir, 'CREDITS.md').slice(root.length)}`);
}
if (missing) process.exitCode = 1;
